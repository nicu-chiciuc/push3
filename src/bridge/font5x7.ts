/** Draw text into an RGB565 Uint16Array (960x160). Returns the drawn width. */
export function drawText(pixels: Uint16Array, text: string, x0: number, y0: number, scale: number, color565: number, width = 960): number {
  let x = x0;
  for (const ch of text.toUpperCase()) {
    const g = G[ch] ?? G[' ']!;
    for (let i = 0; i < 35; i++) {
      if (g[i] !== '#') continue;
      const gx = x + (i % 5) * scale;
      const gy = y0 + Math.floor(i / 5) * scale;
      for (let dy = 0; dy < scale; dy++)
        for (let dx = 0; dx < scale; dx++) pixels[(gy + dy) * width + gx + dx] = color565;
    }
    x += 6 * scale;
  }
  return x - x0 - scale;
}

export const textWidth = (text: string, scale: number): number => text.length * 6 * scale - scale;
export const rgb565 = (r: number, g: number, b: number): number => ((b >> 3) << 11) | ((g >> 2) << 5) | (r >> 3);
